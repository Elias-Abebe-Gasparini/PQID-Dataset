"""
Apply the post-freeze QDiff repository-license update.

The QDiff source rows in PQID were acquired under the historical
``wjy99-c/QDiff`` GitHub address and were previously treated as no-license
rows. The same project contents are publicly available under
``UCLA-SEAL/QDiff`` with a root BSD 3-Clause LICENSE file. This script records
that alias evidence and updates only rows sourced from QDiff in the canonical
construction splits.

Release views are still generated by export_license_valid_release_views.py;
this script only updates row-level license metadata consumed by those views.
"""

