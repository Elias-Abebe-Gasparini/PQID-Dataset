CACHE_FILE = PROCESSED_DIR / "repo_license_cache.jsonl"
EVIDENCE_DIR = PROCESSED_DIR / "license_evidence"
EVIDENCE_FILE = EVIDENCE_DIR / "qdiff_bsd3_license_update_2026-05-09.json"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Count affected rows and write nothing.",
    )
    return parser.parse_args()


def iter_jsonl(path: Path):
    with path.open("r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


def write_jsonl_row(handle, row: dict[str, Any]) -> None:
    handle.write(json.dumps(row, ensure_ascii=False) + "\n")


def is_qdiff_row(row: dict[str, Any]) -> bool:
    metadata = row.get("metadata") or {}
    owner = str(metadata.get("repo_owner") or "").strip()
    name = str(metadata.get("repo_name") or "").strip()
    if name == REPO_NAME and owner in {HISTORICAL_REPO_OWNER, CURRENT_REPO_OWNER}:
        return True
    original_url = str(metadata.get("original_url") or "").strip()
    return original_url.startswith(f"https://github.com/{HISTORICAL_OWNER_REPO}/") or original_url.startswith(
        f"https://github.com/{CURRENT_OWNER_REPO}/"
    )


def patch_metadata(row: dict[str, Any]) -> dict[str, Any]:
    patched = dict(row)
    metadata = dict(patched.get("metadata") or {})
    if metadata.get("license_override_version") == UPDATE_VERSION and isinstance(
        metadata.get("license_previous_state"), dict
    ):
        previous = metadata["license_previous_state"]
    else:
        previous = {
            "repo_license": metadata.get("repo_license"),
            "license_category": metadata.get("license_category"),
            "license_evidence_source": metadata.get("license_evidence_source"),
            "license_detection_method": metadata.get("license_detection_method"),
        }
    metadata.update(
        {
            "repo_license": LICENSE_SPDX,
            "license_category": LICENSE_CATEGORY,
            "license_evidence_source": "github_license_file",
            "license_detection_method": "manual_post_freeze_repository_alias_license_update",
            "license_evidence_url": LICENSE_URL,
            "license_evidence_commit": LICENSE_COMMIT,
            "license_evidence_commit_url": LICENSE_COMMIT_URL,
            "license_evidence_commit_date": LICENSE_COMMIT_DATE,
            "license_evidence_file_sha": LICENSE_FILE_SHA,
            "license_original_owner_repo": HISTORICAL_OWNER_REPO,
            "license_current_owner_repo": CURRENT_OWNER_REPO,
            "license_alias_match_count": len(MATCHED_ALIAS_EVIDENCE),
            "license_override_version": UPDATE_VERSION,
            "license_override_reason": (
                "QDiff source rows were acquired under the historical "
                "wjy99-c/QDiff address; the same project contents are available "
                "under UCLA-SEAL/QDiff with a root BSD 3-Clause LICENSE file."
            ),
            "license_previous_state": previous,
            "distribution_rights_status": "redistributable_permissive",
            "license_resolution_status": "resolved",
            "public_release_bucket": "public_open",
            "release_view_membership": "public_open",
            "permission_response_status": "upstream_license_file_verified",
        }
    )
    patched["metadata"] = metadata
    return patched


def patch_split(path: Path, *, dry_run: bool) -> dict[str, Any]:
    tmp_path = Path(str(path) + f".{UPDATE_VERSION}.tmp")
    input_rows = 0
    patched_rows = 0
    previous_categories: Counter[str] = Counter()
    previous_licenses: Counter[str] = Counter()

    out_handle = None
    try:
        if not dry_run:
            out_handle = tmp_path.open("w", encoding="utf-8")
        for row in iter_jsonl(path):
            input_rows += 1
            if is_qdiff_row(row):
                metadata = row.get("metadata") or {}
                previous_categories[str(metadata.get("license_category") or "<missing>")] += 1
                previous_licenses[str(metadata.get("repo_license") or "<missing>")] += 1
                patched_rows += 1
                row = patch_metadata(row)
            if out_handle is not None:
                write_jsonl_row(out_handle, row)
    finally:
        if out_handle is not None:
            out_handle.close()

    if not dry_run:
        tmp_path.replace(path)

    return {
        "input_rows": input_rows,
        "patched_rows": patched_rows,
        "previous_license_category_counts": dict(sorted(previous_categories.items())),
        "previous_repo_license_counts": dict(sorted(previous_licenses.items())),
    }


def load_cache(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def patch_cache(path: Path, *, dry_run: bool) -> dict[str, Any]:
    records = load_cache(path)
    found = False
    old_record = None
    new_record = {
        "owner_repo": HISTORICAL_OWNER_REPO,
        "repo_license": LICENSE_SPDX,
        "license_category": LICENSE_CATEGORY,
        "license_evidence_source": "github_license_file",
        "license_detection_method": "manual_post_freeze_repository_alias_license_update",
        "license_evidence_url": LICENSE_URL,
        "license_evidence_commit": LICENSE_COMMIT,
        "license_evidence_commit_url": LICENSE_COMMIT_URL,
        "license_evidence_commit_date": LICENSE_COMMIT_DATE,
        "license_evidence_file_sha": LICENSE_FILE_SHA,
        "license_original_owner_repo": HISTORICAL_OWNER_REPO,
        "license_current_owner_repo": CURRENT_OWNER_REPO,
        "license_alias_match_count": len(MATCHED_ALIAS_EVIDENCE),
        "license_override_version": UPDATE_VERSION,
    }
    for index, record in enumerate(records):
        if record.get("owner_repo") == HISTORICAL_OWNER_REPO:
            found = True
            old_record = record
            records[index] = new_record
            break
    if not found:
        records.append(new_record)

    current_record = dict(new_record)
    current_record["owner_repo"] = CURRENT_OWNER_REPO
    current_record["license_original_owner_repo"] = HISTORICAL_OWNER_REPO
    current_record["license_current_owner_repo"] = CURRENT_OWNER_REPO
    if not any(record.get("owner_repo") == CURRENT_OWNER_REPO for record in records):
        records.append(current_record)

    if not dry_run:
        tmp_path = Path(str(path) + f".{UPDATE_VERSION}.tmp")
        with tmp_path.open("w", encoding="utf-8") as handle:
            for record in records:
                write_jsonl_row(handle, record)
        tmp_path.replace(path)

    return {
        "cache_file": format_display_path(path),
        "cache_record_found": found,
        "previous_cache_record": old_record,
        "new_cache_record": new_record,
        "current_owner_cache_record": current_record,
    }


def build_evidence(split_summaries: dict[str, Any], cache_summary: dict[str, Any]) -> dict[str, Any]:
    total_patched = sum(item["patched_rows"] for item in split_summaries.values())
    return {
        "evidence_version": UPDATE_VERSION,
        "historical_owner_repo": HISTORICAL_OWNER_REPO,
        "current_owner_repo": CURRENT_OWNER_REPO,
        "repo_license": LICENSE_SPDX,
        "license_category": LICENSE_CATEGORY,
        "license_url": LICENSE_URL,
        "license_file_sha": LICENSE_FILE_SHA,
        "license_commit": LICENSE_COMMIT,
        "license_commit_url": LICENSE_COMMIT_URL,
        "license_commit_date": LICENSE_COMMIT_DATE,
        "license_commit_message": "Initial commit",
        "license_copyright": "Copyright (c) 2021, UCLA Software Engineering Analysis Laboratory (SEAL)",
        "matched_alias_evidence": MATCHED_ALIAS_EVIDENCE,
        "interpretation": (
            "Rows sourced from historical wjy99-c/QDiff are reclassified from "
            "no_license to permissive/BSD-3-Clause based on the root LICENSE "
            "file in UCLA-SEAL/QDiff and matched file-path/blob evidence."
        ),
        "scope_note": (
            "This resolves repository-level redistribution evidence for the "
            "QDiff repository contents used by PQID. It does not independently "
            "audit any third-party code that may be embedded in that repository."
        ),
        "split_summaries": split_summaries,
        "total_patched_rows": total_patched,
        "cache_summary": cache_summary,
    }


def main() -> None:
    args = parse_args()
    split_summaries = {}
    for split, path in SPLIT_FILES.items():
        split_summaries[split] = patch_split(path, dry_run=args.dry_run)

    cache_summary = patch_cache(CACHE_FILE, dry_run=args.dry_run)
    evidence = build_evidence(split_summaries, cache_summary)

    if not args.dry_run:
        EVIDENCE_DIR.mkdir(parents=True, exist_ok=True)
        EVIDENCE_FILE.write_text(json.dumps(evidence, ensure_ascii=False, indent=2), encoding="utf-8")

    print("QDiff BSD-3-Clause license update")
    print("  dry run      :", args.dry_run)
    print("  historical   :", HISTORICAL_OWNER_REPO)
    print("  current      :", CURRENT_OWNER_REPO)
    print("  license      :", LICENSE_SPDX)
    print("  commit       :", LICENSE_COMMIT)
    print("  total patched:", f"{evidence['total_patched_rows']:,}")
    for split, stats in split_summaries.items():
        print(f"  {split:<10}: {stats['patched_rows']:,} / {stats['input_rows']:,}")
    if not args.dry_run:
        print("  evidence     :", format_display_path(EVIDENCE_FILE))


if __name__ == "__main__":
    main()
